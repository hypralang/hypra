//! Translates an IR [`Program`] to a PHP file for the `hypra/runtime` package.
//!
//! The file returns an instance of an anonymous `Hypra\Runtime\Page` subclass, so pages never
//! clash by name: `$page = require 'product.php'; $output = $page->render($data);`

use crate::ir::{ActionDef, Channel, Escape, Expr, Op, Program};
use crate::lexer::Pos;
use serde_json::Value as Json;

/// `files` are the source paths, indexed by `Pos::file`, for error locations.
pub fn emit(program: &Program, files: &[&str]) -> String {
    let mut w = Writer { out: String::new(), indent: 0, files };
    let entry = files.first().copied().unwrap_or("page.hypra");

    w.line("<?php");
    w.blank();
    // the path is only a comment; keep it from ending the comment or PHP mode
    let entry: String = entry.chars().filter(|c| !c.is_control()).collect::<String>().replace("?>", "? >");
    w.line(&format!("// Generated by hypra from {entry}. Do not edit."));
    w.blank();
    w.line("declare(strict_types=1);");
    w.blank();
    w.line("use Hypra\\Runtime\\Context;");
    w.line("use Hypra\\Runtime\\Value;");
    w.blank();
    w.open("return new class extends \\Hypra\\Runtime\\Page {");
    let sources: Vec<String> = files.iter().map(|f| quote(f)).collect();
    // each prop with where it's declared, for the error when data leaves it out
    let props: Vec<String> = program.props.iter().map(|p| format!("{} => {}", quote(&p.name), w.at(p.pos))).collect();
    w.line(&format!("protected const PROPS = [{}];", props.join(", ")));
    w.line(&format!("protected const SOURCES = [{}];", sources.join(", ")));
    w.blank();
    w.line("protected function body(Context $c): void");
    w.open("{");
    w.ops(&program.ops);
    w.close("}");
    w.blank();
    w.line("protected function meta(Context $c): array");
    w.open("{");
    let meta = &program.meta;
    let optional = |w: &Writer, e: &Option<Expr>| e.as_ref().map_or("null".to_string(), |e| w.expr(e));
    let fields = [
        ("title", w.expr(&meta.title)),
        ("description", optional(&w, &meta.description)),
        ("lang", w.expr(&meta.lang)),
        ("canonical", optional(&w, &meta.canonical)),
    ];
    w.open("return [");
    for (key, value) in fields {
        w.line(&format!("'{key}' => {value},"));
    }
    w.close("];");
    w.close("}");
    w.close("};");
    w.out
}

struct Writer<'a> {
    out: String,
    indent: usize,
    files: &'a [&'a str],
}

impl Writer<'_> {
    fn line(&mut self, text: &str) {
        self.out.push_str(&"    ".repeat(self.indent));
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn blank(&mut self) {
        self.out.push('\n');
    }

    fn open(&mut self, text: &str) {
        self.line(text);
        self.indent += 1;
    }

    fn close(&mut self, text: &str) {
        self.indent -= 1;
        self.line(text);
    }

    fn ops(&mut self, ops: &[Op]) {
        for op in ops {
            match op {
                Op::Html(text) => self.line(&format!("$c->html({});", quote(text))),
                Op::Md(text) => self.line(&format!("$c->md({});", quote(text))),
                Op::Value { to, expr, escape } => {
                    let method = match (to, escape) {
                        (Channel::Html, Escape::Html) => "htmlText",
                        (Channel::Html, Escape::Url) => "htmlUrl",
                        (Channel::Html, Escape::Script) => "htmlScript",
                        (Channel::Html, Escape::ScriptJson) => "htmlScriptJson",
                        (Channel::Html, Escape::Raw) => "htmlRaw",
                        (Channel::Html, Escape::JsonHtml) => "htmlJson",
                        (Channel::Md, Escape::Markdown) => "mdText",
                        (Channel::Md, Escape::MarkdownUrl) => "mdUrl",
                        (Channel::Md, Escape::MarkdownCode) => "mdCode",
                        (Channel::Md, Escape::MarkdownFence) => "mdFence",
                        (Channel::Md, Escape::Json) => "mdJson",
                        (to, escape) => unreachable!("lowering never writes {escape:?} to {to:?}"),
                    };
                    self.line(&format!("$c->{method}({});", self.expr(expr)));
                }
                Op::For { var, list, source, pos, body, .. } => {
                    let each = format!("$c->each({}, {}, {})", self.expr(list), quote(source), self.at(*pos));
                    self.open(&format!("foreach ({each} as $v{var}) {{"));
                    self.ops(body);
                    self.close("}");
                }
                Op::If { cond, then, otherwise } => {
                    self.open(&format!("if (Value::truthy({})) {{", self.expr(cond)));
                    self.ops(then);
                    if !otherwise.is_empty() {
                        self.indent -= 1;
                        self.open("} else {");
                        self.ops(otherwise);
                    }
                    self.close("}");
                }
                Op::Set { var, value } => self.line(&format!("$v{var} = {};", self.expr(value))),
                Op::Action(def) => self.action(def),
                Op::FormFields { indent, action } => {
                    let action = action.as_ref().map_or("null".to_string(), |a| self.expr(a));
                    self.line(&format!("$c->formFields({}, {action});", quote(indent)));
                }
                Op::AlternateLink { indent, .. } => self.line(&format!("$c->alternateLink({});", quote(indent))),
            }
        }
    }

    fn action(&mut self, def: &ActionDef) {
        let head = format!(
            "$c->action({}, {}, {}, {}, [",
            quote(&def.name),
            self.expr(&def.description),
            quote(&def.method),
            self.expr(&def.endpoint)
        );
        self.open(&head);
        for p in &def.params {
            let source = match &p.value {
                Some(value) => format!("'value' => {}", self.expr(value)),
                None => format!("'schema' => {}", literal(&p.schema)),
            };
            self.line(&format!("['name' => {}, {source}, 'required' => {}],", quote(&p.name), p.required));
        }
        self.close("]);");
    }

    fn expr(&self, expr: &Expr) -> String {
        match expr {
            Expr::Lit(value) => literal(value),
            Expr::Data { path, pos, .. } => format!("$c->data({}, {})", list(path), self.at(*pos)),
            Expr::Var { id, path, .. } if path.is_empty() => format!("$v{id}"),
            Expr::Var { id, name, path, pos, .. } => {
                format!("$c->get($v{id}, {}, {}, {})", quote(name), list(path), self.at(*pos))
            }
            Expr::Concat(parts) => {
                let parts: Vec<String> = parts.iter().map(|p| self.expr(p)).collect();
                format!("$c->concat({})", parts.join(", "))
            }
            Expr::Equals(value, text) => format!("(Value::display({}) === {})", self.expr(value), quote(text)),
        }
    }

    /// A source location for runtime errors, e.g. `'examples/product.hypra:22:16'`.
    fn at(&self, pos: Pos) -> String {
        let file = self.files.get(pos.file).copied().unwrap_or("?");
        quote(&format!("{file}:{}:{}", pos.line, pos.col))
    }
}

fn list(items: &[String]) -> String {
    let items: Vec<String> = items.iter().map(|i| quote(i)).collect();
    format!("[{}]", items.join(", "))
}

/// A PHP literal for a JSON value. Empty objects stay objects so they encode as `{}`.
fn literal(value: &Json) -> String {
    match value {
        Json::Null => "null".into(),
        Json::Bool(b) => b.to_string(),
        Json::Number(n) => n.to_string(),
        Json::String(s) => quote(s),
        Json::Array(items) => {
            let items: Vec<String> = items.iter().map(literal).collect();
            format!("[{}]", items.join(", "))
        }
        Json::Object(map) if map.is_empty() => "new \\stdClass()".into(),
        Json::Object(map) => {
            let entries: Vec<String> = map.iter().map(|(k, v)| format!("{} => {}", quote(k), literal(v))).collect();
            format!("[{}]", entries.join(", "))
        }
    }
}

/// A PHP string literal. Single-quoted unless it contains line breaks or tabs,
/// which are written as escapes in a double-quoted string so every op stays on one line.
fn quote(text: &str) -> String {
    if !text.contains(['\n', '\r', '\t']) {
        return format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"));
    }
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\\' | '"' | '$' => {
                out.push('\\');
                out.push(c);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
